"""Idempotent, repo-scoped cleanup. Never deletes releases, tags, source or runs."""
import json
import os
import urllib.error
import urllib.request
from pathlib import Path

REPOSITORY = 'joinsnipe/PDF'
REPO_ID = 1419943509

def api(path, method='GET'):
    request = urllib.request.Request(f'https://api.github.com/repos/{REPOSITORY}/{path}', method=method, headers={
        'Authorization': 'Bearer ' + os.environ['GH_TOKEN'],
        'Accept': 'application/vnd.github+json', 'X-GitHub-Api-Version': '2022-11-28',
    })
    try:
        with urllib.request.urlopen(request, timeout=30) as response:
            return json.load(response) if response.status != 204 else None
    except urllib.error.HTTPError as error:
        if error.code == 404 and method == 'GET':
            return None
        raise

def verify_artifact(artifact, row, release, run):
    expected = {f"PDF-{row['tag'][1:]}-{p}.zip" for p in ('windows-x64', 'macos-arm64', 'macos-x64', 'web')} | {'SHA256SUMS.txt'}
    assets = {a['name'] for a in release.get('assets', []) if a['state'] == 'uploaded' and a['size'] > 0}
    source = artifact.get('workflow_run', {})
    if (release.get('draft') or release.get('tag_name') != row['tag'] or not expected <= assets
        or artifact['id'] != row['id'] or artifact['name'] != 'PDF-distributions'
        or artifact['size_in_bytes'] != row['bytes'] or source.get('id') != row['run_id']
        or source.get('head_sha') != row['sha'] or source.get('head_branch') != 'main'
        or source.get('repository_id') != REPO_ID or source.get('head_repository_id') != REPO_ID
        or run.get('status') != 'completed' or run.get('conclusion') != 'success'):
        raise RuntimeError(f"No se cumplen las comprobaciones del artefacto {row['id']}.")

def main():
    if os.environ.get('GITHUB_REPOSITORY') != REPOSITORY:
        raise SystemExit('Esta limpieza solo puede operar en joinsnipe/PDF.')
    rows = json.loads(Path(__file__).with_name('actions-cleanup-20261016.json').read_text())
    planned = []
    # Verify the complete plan before deleting the first artifact.
    for row in rows:
        artifact = api(f"actions/artifacts/{row['id']}")
        if artifact is None:
            print(f"{row['id']}: ya eliminado o caducado.")
            continue
        release = api(f"releases/tags/{row['tag']}")
        run = api(f"actions/runs/{row['run_id']}")
        if not release or not run:
            raise RuntimeError('Falta la versión publicada o la ejecución de referencia.')
        verify_artifact(artifact, row, release, run)
        planned.append(row)
    for row in planned:
        api(f"actions/artifacts/{row['id']}", 'DELETE')
        print(f"Eliminado artefacto {row['id']}: {row['bytes']} bytes; descarga conservada en {row['tag']}.")
    # setup-node caches are reproducible and no longer generated by this workflow.
    caches = []
    page = 1
    while True:
        result = api(f'actions/caches?per_page=100&page={page}')
        current = result['actions_caches']
        caches.extend(c for c in current if c['key'].startswith('node-cache-'))
        if len(current) < 100:
            break
        page += 1
    for cache in caches:
        api(f"actions/caches/{cache['id']}", 'DELETE')
        print(f"Eliminada caché npm {cache['id']}: {cache['size_in_bytes']} bytes.")
    if any(api(f"actions/artifacts/{row['id']}") is not None for row in rows):
        raise RuntimeError('Quedan artefactos del inventario por eliminar.')
    summary = (f"PDF: eliminados {len(planned)} artefactos, {sum(r['bytes'] for r in planned):,} bytes. "
               f"Eliminadas {len(caches)} cachés npm. Versiones y descargas conservadas.\n")
    print(summary)
    if os.environ.get('GITHUB_STEP_SUMMARY'):
        with open(os.environ['GITHUB_STEP_SUMMARY'], 'a') as output:
            output.write(summary)

if __name__ == '__main__':
    main()
